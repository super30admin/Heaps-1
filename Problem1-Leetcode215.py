#Time Complexity: O(n log k) where n is the length of nums and k is the size of the heap
#Space Complexity: O(k) where k is the size of the heap

import heapq

class Solution(object):
    def findKthLargest(self, nums, k):
        """
        :type nums: List[int]
        :type k: int
        :rtype: int
        """
        pq = []
        for num in nums:
            heapq.heappush(pq, num)
            if len(pq) > k:
                heapq.heappop(pq)
        return pq[0]

        